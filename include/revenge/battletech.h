#ifndef REVENGE_BATTLETECH_H
#define REVENGE_BATTLETECH_H

/* BattleTech rule and force geometry constants recovered from the original
 * executable. Keep these names at call sites so game rules remain distinct
 * from display dimensions and packed-file sizes that happen to share values. */
enum
{
	BATTLETECH_D6_FACE_COUNT = 0x06,
	BATTLETECH_D6_CANDIDATE_MASK = 0x07,
	BATTLETECH_2D6_MINIMUM = 0x02,
	BATTLETECH_2D6_CRITICAL_TARGET = 0x08,
	BATTLETECH_MAX_TO_HIT_TARGET = 0x0A,
	BATTLETECH_2D6_NATURAL_TWELVE = 0x0C,
	BATTLETECH_CATASTROPHIC_LOCATION_DAMAGE = 0x64,
	BATTLETECH_DIRECTION_COUNT = 0x08,
	LANCE_UNIT_COUNT = 0x04,
	TACTICAL_FORCE_UNIT_COUNT = 0x0C,
	TACTICAL_FORCE_LAST_UNIT_OFFSET = TACTICAL_FORCE_UNIT_COUNT - 0x01,
	TACTICAL_UNIT_COUNT = TACTICAL_FORCE_UNIT_COUNT * 0x02,
	FRIENDLY_FORCE_FIRST_UNIT = 0x00,
	ENEMY_FORCE_FIRST_UNIT = TACTICAL_FORCE_UNIT_COUNT
};

#endif
